function shuffle(arr, rng) {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(rng() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; }
  return a;
}

/** 各段階から perLevel 問を選ぶ。まだ出していない問題を優先する。戻り値は段階1→2→3の順 */
export function pickItems(rng, seenIds = [], perLevel = 8) {
  const seen = new Set(seenIds);
  const out = [];
  for (const level of [1, 2, 3]) {
    const pool = BANK.filter((q) => q.level === level);
    const fresh = shuffle(pool.filter((q) => !seen.has(q.id)), rng);
    const old = shuffle(pool.filter((q) => seen.has(q.id)), rng);
    out.push(...shuffle(fresh.concat(old).slice(0, perLevel), rng));
  }
  return out;
}
