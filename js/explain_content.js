export const topicById = (id) => TOPICS.find((t) => t.id === id);

/** 説明1つ分の画面部品を作る */
export function renderVersion(topic, key) {
  const v = topic.versions[key];
  const wrap = el('div', { class: 'expl' });
  if (key === 'diagram') {
    wrap.append(v.svg());
    v.caption.forEach((c) => wrap.append(el('p', { class: 'cap', text: c })));
  } else {
    v.blocks.forEach((b) => wrap.append(b.t === 'f' ? el('pre', { class: 'formula', text: b.s }) : el('p', { text: b.s })));
  }
  return wrap;
}
