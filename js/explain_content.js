  const node = (x, y, w, t, c) => [box(x - w / 2, y - 14, w, 28, c), T(x, y + 5, t, 'sv-on')];
  const ln = (x1, y1, x2, y2) => s('line', { x1, y1, x2, y2, class: 'sv-line' });
