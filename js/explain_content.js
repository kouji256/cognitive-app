function diagK5() {
  const cx = 170, cy = 100, R = 78, names = ['A', 'B', 'C', 'D', 'E'];
  const pts = names.map((_, i) => [cx + R * Math.cos(((-90 + 72 * i) * Math.PI) / 180), cy + R * Math.sin(((-90 + 72 * i) * Math.PI) / 180)]);
  const kids = [];
  for (let i = 0; i < 5; i++) for (let j = i + 1; j < 5; j++) kids.push(s('line', { x1: pts[i][0], y1: pts[i][1], x2: pts[j][0], y2: pts[j][1], class: 'sv-line' }));
  pts.forEach(([x, y], i) => kids.push(s('circle', { cx: x, cy: y, r: 13, class: 'sv-b' }), T(x, y + 5, names[i], 'sv-on')));
  return svgRoot(340, 200, '5点から2点を選ぶ組を線で結んだ図(線は10本)', kids);
}
