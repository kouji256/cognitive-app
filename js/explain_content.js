// ---------- SVG 部品(内容は textContent / setAttribute のみで作る) ----------
const svgRoot = (w, h, label, ...kids) => s('svg', { viewBox: `0 0 ${w} ${h}`, class: 'diagram', role: 'img', 'aria-label': label }, ...kids);
const T = (x, y, t, cls = 'sv-t', anchor = 'middle') => s('text', { x, y, class: cls, 'text-anchor': anchor }, t);
const box = (x, y, w, h, c) => s('rect', { x, y, width: w, height: h, class: 'sv-' + c });

function diagEuclid() {
  const u = 6, x0 = 16, y0 = 12;
  const sq = (x, y, n, c) => [box(x0 + x * u, y0 + y * u, n * u, n * u, c), T(x0 + (x + n / 2) * u, y0 + (y + n / 2) * u + 5, `${n}×${n}`, 'sv-on')];
  return svgRoot(330, 140, '48×18 の長方形を、正方形で敷き詰めた図',
    sq(0, 0, 18, 'b'), sq(18, 0, 18, 'b'), sq(36, 0, 12, 'y'), sq(36, 12, 6, 'g'), sq(42, 12, 6, 'g'),
    T(x0 + 144, 134, '全体 48×18', 'sv-t'));
}
function diagBsearch() {
  const vals = [100, 50, 25, 12, 6, 3, 1, 0];
  const kids = vals.map((v, i) => [
    T(8, 22 + i * 26, `${i}回後`, 'sv-t', 'start'),
    v ? box(64, 8 + i * 26, v * 3, 20, 'b') : null,
    T(64 + v * 3 + 8, 23 + i * 26, `${v}個`, 'sv-t', 'start'),
  ]);
  return svgRoot(420, 222, '比較のたびに候補の数が半分になる棒グラフ', kids);
}
function diagExpect() {
  const rows = [['1等 1000円 × 0.01 = 10', 10, 'b'], ['2等 100円 × 0.1 = 10', 10, 'y'], ['はずれ 0円 × 0.89 = 0', 0, 'g']];
  const kids = [];
  rows.forEach(([label, v, c], i) => {
    kids.push(T(8, 20 + i * 36, label, 'sv-t', 'start'));
    if (v) kids.push(box(8, 26 + i * 36, v * 10, 14, c));
  });
  kids.push(T(8, 134, '寄与を合計(横に並べる)', 'sv-t', 'start'));
  kids.push(box(8, 142, 100, 18, 'b'), box(108, 142, 100, 18, 'y'));
  kids.push(T(218, 156, '= 期待値 20円', 'sv-t', 'start'));
  return svgRoot(340, 172, '値×確率の寄与を足し合わせる図', kids);
}
